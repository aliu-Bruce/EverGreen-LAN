"""从 lockfile 生成 THIRD-PARTY-NOTICES.md。

静态链接使最终发布的二进制构成组合作品：其中每个 crate 的许可证都需要一并复现。
该脚本以机械化的方式维护这份清单，而非凭乐观估计。
"""

from __future__ import annotations

import json
import os
import re
from collections import defaultdict
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CARGO_SRC = Path(os.environ["USERPROFILE"]) / ".cargo" / "registry" / "src"
TARGET = ROOT / "THIRD-PARTY-NOTICES.md"


def crate_licence(name: str, version: str) -> str:
    for index in CARGO_SRC.glob("index.crates.io-*"):
        manifest = index / f"{name}-{version}" / "Cargo.toml"
        if manifest.is_file():
            text = manifest.read_text(encoding="utf-8", errors="ignore")
            match = re.search(r'^license\s*=\s*"([^"]+)"', text, re.M)
            if match:
                return match.group(1)
            if re.search(r"^license-file\s*=", text, re.M):
                return "<license-file>"
    # 面向其他目标平台（Linux、macOS、UEFI）的 crate 不会下载到本机，
    # 此时向 crates.io 查询许可证，而不是猜测。
    try:
        import urllib.request

        with urllib.request.urlopen(
            f"https://crates.io/api/v1/crates/{name}/{version}", timeout=10
        ) as response:
            data = json.loads(response.read().decode("utf-8"))
        licence = data.get("version", {}).get("license")
        if licence:
            return licence
    except Exception:
        pass
    return "<not resolved>"


def rust_packages() -> dict[str, list[str]]:
    text = (ROOT / "Cargo.lock").read_text(encoding="utf-8")
    grouped: dict[str, list[str]] = defaultdict(list)
    for block in text.split("[[package]]")[1:]:
        name = re.search(r'name = "([^"]+)"', block)
        version = re.search(r'version = "([^"]+)"', block)
        if not name or not version:
            continue
        # 本项目自身的 crate 由项目 LICENSE 覆盖。
        if name.group(1).startswith("egl-"):
            continue
        grouped[crate_licence(name.group(1), version.group(1))].append(
            f"{name.group(1)} {version.group(1)}"
        )
    return grouped


def npm_packages() -> dict[str, list[str]]:
    lock_path = ROOT / "package-lock.json"
    if not lock_path.is_file():
        return {}
    lock = json.loads(lock_path.read_text(encoding="utf-8"))
    grouped: dict[str, list[str]] = defaultdict(list)
    for key, meta in lock.get("packages", {}).items():
        if not key.startswith("node_modules/") or meta.get("dev"):
            continue
        # 本项目自身的 workspace 包由项目 LICENSE 覆盖。
        if meta.get("link") or meta.get("name", "").startswith("@egl/"):
            continue
        licence = meta.get("license")
        if not licence:
            pkg_json = ROOT / key / "package.json"
            try:
                licence = json.loads(pkg_json.read_text(encoding="utf-8")).get("license")
            except Exception:
                licence = None
        if isinstance(licence, dict):
            licence = licence.get("type")
        grouped[licence or "<not declared>"].append(key.removeprefix("node_modules/"))
    return grouped


def render() -> str:
    rust = rust_packages()
    npm = npm_packages()

    lines: list[str] = []
    lines.append("# Third-party notices")
    lines.append("")
    lines.append(f"Generated by `scripts/third-party-notices.py` on {date.today().isoformat()}.")
    lines.append("")
    lines.append(
        "EverGreen LAN itself is licensed under the Apache License 2.0 (see `LICENSE`). "
        "The components below keep their own licences and are reproduced here as required."
    )
    lines.append("")
    lines.append("## Bundled binaries and assets")
    lines.append("")
    lines.append("| Component | Licence |")
    lines.append("|---|---|")
    lines.append("| Wintun (`wintun.dll`, WireGuard LLC) | Prebuilt Binaries License, <https://www.wintun.net/> |")
    lines.append("| Instrument Serif, Inter Tight, IBM Plex Mono | SIL Open Font License 1.1 |")
    lines.append(
        "| WebView2 runtime | Distributed by Microsoft with Windows; not redistributed here |"
    )
    lines.append("")

    def section(title: str, grouped: dict[str, list[str]]) -> None:
        total = sum(len(v) for v in grouped.values())
        lines.append(f"## {title} ({total} packages)")
        lines.append("")
        for licence in sorted(grouped, key=lambda k: (-len(grouped[k]), k)):
            packages = sorted(grouped[licence])
            lines.append(f"### {licence} — {len(packages)}")
            lines.append("")
            lines.append("```")
            lines.extend(packages)
            lines.append("```")
            lines.append("")

    section("Rust crates (Cargo.lock)", rust)
    section("npm packages shipped in the bundle", npm)
    return "\n".join(lines)


def main() -> None:
    text = render()
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.name} ({len(text)} chars)")


if __name__ == "__main__":
    main()
